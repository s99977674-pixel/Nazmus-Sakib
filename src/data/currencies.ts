export function getCurrency(code: string): Currency {
  const found = ALL_CURRENCIES.find((c) => c.code.toUpperCase() === code.toUpperCase());
  if (found) return found;
  return {
    code: code.toUpperCase(),
    name: code.toUpperCase(),
    symbol: code.toUpperCase(),
    decimals: 2,
  };
}

export function searchCurrencies(query: string): Currency[] {
  const trimmed = query.trim().toLowerCase();
  if (!trimmed) return ALL_CURRENCIES;

  return ALL_CURRENCIES.filter(
    (c) =>
      c.code.toLowerCase().includes(trimmed) ||
      c.name.toLowerCase().includes(trimmed) ||
      c.symbol.toLowerCase().includes(trimmed)
  );
}

export function formatCurrencyAmount(amount: number, currency: Currency): string {
  if (isNaN(amount) || !isFinite(amount)) return `${currency.symbol}0.00`;
  
  // Professional thousand separators and exact decimal precision
  const parts = amount.toLocaleString('en-US', {
    minimumFractionDigits: currency.decimals,
    maximumFractionDigits: currency.decimals,
  });

  return `${currency.symbol}${parts}`;
}
